import assert from "node:assert/strict";
import {loadData} from "./data.mjs";
const {allDays,allWeeks,feed,weeklyFeed} = loadData();
assert(Array.isArray(allDays) && Array.isArray(allWeeks));
assert.equal(feed.schemaVersion,1);
assert.equal(weeklyFeed.schemaVersion,1);
assert(feed.issues.length<=7);
assert(weeklyFeed.weeks.length<=52);
const sorted = arr => arr.every((item,index)=>index===0||item<=arr[index-1]);
assert(sorted(allDays.map(x=>x.date)),"Daily source file dates not descending");
assert(sorted(allWeeks.map(x=>x.weekEnding)),"Weekly source file dates not descending");
console.log("Daily archive "+allDays.length+" source files ("+feed.issues.length+" in recent window), weekly archive "+allWeeks.length+" source files ("+weeklyFeed.weeks.length+" published)");
